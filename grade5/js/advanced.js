/* 進階問答：題目物件 {q, sp, vis, opts, keep, hint, ex, trap}；有 ans 時改用小鍵盤（unit、keys 同 quiz） */
function xquiz(st, rounds) {
  let i = 0;
  function show() {
    if (i >= rounds.length) { api.finish(); return; }
    let r = rounds[i]; if (typeof r === 'function') r = r();
    const typed = r.ans !== undefined;
    st.innerHTML = `${dots(i, rounds.length)}<div class="qvis">${r.vis || ''}</div><div class="${typed ? 'kwrap' : 'opts'}"></div><div class="xpl" hidden></div>`;
    api.say(r.q, r.sp);
    const done = () => {
      const x = $('.xpl', st), last = i === rounds.length - 1;
      x.innerHTML = `<div class="xpl-ex">📖 詳解：${r.ex}</div>${r.trap ? `<div class="xpl-trap">⚠️ 小心陷阱：${r.trap}</div>` : ''}<div class="center"><button class="btn mint xpl-next" type="button">${last ? '完成 🎉' : '下一題 ➜'}</button></div>`;
      x.hidden = false;
      speak('詳解。' + r.ex + (r.trap ? '小心陷阱。' + r.trap : ''));
      $('.xpl-next', x).onclick = () => { i++; show(); };
      x.scrollIntoView && x.scrollIntoView({ block: 'nearest', behavior: 'smooth' });
    };
    if (typed) return keypad($('.kwrap', st), r.ans, done, r.hint, r.unit, r.keys);
    const ops = $('.opts', st);
    (r.keep ? r.opts : shuffle(r.opts)).forEach(o => ops.appendChild(optBtn(o, done, r.hint)));
  }
  show();
}

